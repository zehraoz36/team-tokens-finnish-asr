"""Data checks required by the Project 3 split rules.

Reads only the committed clip lists in data/*.csv and writes results/data_checks.md:
* per split: speakers, utterances, hours
* speaker overlap between train and every dev/test split
* test (and dev) sentences that appear word for word in the training set
* how concentrated the training speakers are

Run from the repository root:  python scripts/data_checks.py
"""

import os

import pandas as pd

SPLITS = ["train", "dev_cv", "dev_parl", "test_cv", "test_parl", "test_fleurs"]
OUT = "results/data_checks.md"


def load():
    return {s: pd.read_csv(f"data/{s}.csv", keep_default_na=False, dtype={"speaker": str}) for s in SPLITS}


def main():
    d = load()
    train = d["train"]
    train_spk = set(train.speaker)
    train_txt = set(train.text)
    lines = ["# Data checks", "",
             "Generated by `scripts/data_checks.py` from the clip lists in `data/`.",
             "Sentences are compared after the project normalization (`text` column).", ""]

    lines += ["## Splits", "",
              "| Split | Utterances | Hours | Speakers | Speakers shared with train | Sentences found word for word in train |",
              "|---|---:|---:|---:|---:|---:|"]
    for s in SPLITS:
        x = d[s]
        hours = x.duration.astype(float).sum() / 3600
        if s == "test_fleurs":
            spk, shared = "not provided", "–"   # the `speaker` column holds FLEURS sentence ids
        else:
            spk = f"{x.speaker.nunique():,}"
            shared = "–" if s == "train" else f"{len(set(x.speaker) & train_spk)}"
        if s == "train":
            verb = "–"
        else:
            n = int(x.text.isin(train_txt).sum())
            verb = f"{n} / {len(x):,} ({100 * n / len(x):.1f}%)"
        lines.append(f"| {s} | {len(x):,} | {hours:.2f} | {spk} | {shared} | {verb} |")

    lines += ["", "FLEURS does not provide speaker IDs: its `speaker` column holds the FLEURS sentence id "
              f"({d['test_fleurs'].speaker.nunique()} ids = {d['test_fleurs'].text.nunique()} distinct sentences, "
              f"each read by several speakers, {len(d['test_fleurs'])} clips).", ""]

    # verbatim overlap details
    lines += ["## Test sentences that also occur in train", ""]
    for s in ["test_cv", "test_parl", "test_fleurs"]:
        x = d[s]
        hit = x[x.text.isin(train_txt)]
        lines.append(f"**{s}: {len(hit)} clip(s), {hit.text.nunique()} distinct sentence(s).**")
        if len(hit):
            words = hit.text.str.split().str.len()
            lines.append(f"Length of these sentences: median {int(words.median())} words, max {int(words.max())}. "
                         "Most frequent:")
            lines.append("")
            for t, c in hit.text.value_counts().head(5).items():
                lines.append(f"- `{t}` ({c}×)")
        lines.append("")

    # train speaker concentration
    share = train.groupby("speaker").duration.sum().sort_values(ascending=False) / train.duration.sum()
    clips = train.speaker.value_counts()
    lines += ["## Training speakers", "",
              f"{train.speaker.nunique()} speakers. The largest speaker has {clips.iloc[0]:,} clips "
              f"({100 * clips.iloc[0] / len(train):.1f}% of clips, {100 * share.iloc[0]:.1f}% of audio); "
              f"the three largest have {100 * clips.iloc[:3].sum() / len(train):.1f}% of clips.", "",
              "| Rank | Clips | Share of clips | Share of audio |", "|---:|---:|---:|---:|"]
    for i, (spk, c) in enumerate(clips.items(), 1):
        lines.append(f"| {i} | {c:,} | {100 * c / len(train):.1f}% | {100 * share[spk]:.1f}% |")

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
