"""Build the results tables (Markdown) from results/scores/*.csv.

Baselines and our own trained systems go in separate tables, the three test sets are separate
columns (never averaged), and every row names the exact checkpoint and revision. Re-run after any
new system is evaluated with scripts/asr_eval.py:

    python scripts/make_results_table.py      # writes results/results_table.md
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import asr_eval as E  # noqa: E402

OUT = "results/results_table.md"
TITLES = {"baseline": "Baselines (including our trained GMM-HMM)",
          "contribution": "Our contribution (trained by our group)"}


def main():
    df = E.load_scores()
    best = df.groupby("test_set").wer.min().to_dict()
    lines = ["# Results", "",
             "Generated by `scripts/make_results_table.py` from `results/scores/`. WER / CER in %, "
             "corpus-level, same test clips, references and `normalize()` for every system "
             "(`scripts/asr_eval.py`). Bold = lowest WER on that test set. RTF = compute time / audio time.", ""]
    for role in ("baseline", "contribution"):
        part = df[df.role == role]
        if part.empty:
            continue
        lines += [f"## {TITLES[role]}", "",
                  "| System | Checkpoint | Revision | " + " | ".join(f"{s} WER / CER" for s in E.TEST_SETS) +
                  " | RTF | Hardware, precision |",
                  "|---|---|---|" + "---:|" * len(E.TEST_SETS) + "---:|---|"]
        for system, g in part.groupby("system", sort=False):
            g = g.set_index("test_set")
            cells = []
            for s in E.TEST_SETS:
                if s not in g.index:
                    cells.append("–")
                    continue
                w = f"{g.loc[s, 'wer']:.2f}"
                if g.loc[s, "wer"] == best[s]:
                    w = f"**{w}**"
                cells.append(f"{w} / {g.loc[s, 'cer']:.2f}")
            first = g.iloc[0]
            rtf = f"{g.rtf.min():.3f}–{g.rtf.max():.3f}"
            hw = str(first.hardware).split(" (")[0]
            lines.append(f"| {system} | `{first.checkpoint}` | `{str(first.revision)[:7]}` | " + " | ".join(cells) +
                         f" | {rtf} | {hw}, {first.precision} |")
        lines.append("")
    lines += ["Settings per system: `settings` column of `results/scores/<system>.csv`. "
              "Confidence intervals: `results/bootstrap_ci.md`.", "",
              "Timing caveat: GMM-HMM runs on CPU and excludes precomputed MFCC extraction. Neural systems run "
              "on a T4 GPU with different batch sizes and precision settings. These RTF values describe the "
              "recorded runs, not an equal-conditions architecture speed ranking. See each score file's settings.", "",
              "Whisper baseline-versus-fine-tuned p-values and Holm correction: `results/paired_significance.md`. "
              "Traceable error examples and aggregate diagnostics: `results/error_analysis.md`."]
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
